'use strict';
const assert = require('assert');
const {forDde,km} = require('./dde-profiles');
const b47 = forDde('0F2678'), b57 = forDde('0F1FE8');
assert.strictEqual(forDde('BADBAD'),null);
assert.strictEqual(b47.engine,'B47');
assert.strictEqual(b57.engine,'B57');
assert.strictEqual(b47.regeneration,false,'B47 unverified regen state must not generate messages');
assert.strictEqual(b57.regeneration,true,'B57 existing regeneration must stay enabled');
assert.deepStrictEqual(b47.overview.map(row=>row[0]),['SOOT','ASH','SINCE','AVERAGE']);
assert.deepStrictEqual(b57.overview.map(row=>row[0]),['SOOT','ASH','SINCE','AVERAGE','REQUEST','MODE']);
assert.strictEqual(b47.detail.length,0,'B47 must not use B57 detail DIDs');
assert.ok(b57.detail.some(row=>row[0]==='TEMP'));
assert.ok(b57.detail.some(row=>row[0]==='PRESSURE'));
const raw={SOOT:0x067e,ASH:0x073b,SINCE:0x0006e078,AVERAGE:0x0241};
assert.strictEqual((raw.SOOT*b47.overview[0][3]).toFixed(2),'25.36');
assert.strictEqual((raw.ASH*b47.overview[1][3]).toFixed(2),'28.24');
assert.strictEqual(km({raw:raw.SINCE},b47.distanceFactor).toFixed(2),'450.68');
assert.strictEqual(km({raw:raw.AVERAGE},b47.averageFactor),577);
assert.strictEqual(km({raw:450680},b57.distanceFactor),450.68);
assert.strictEqual(km({raw:577000},b57.averageFactor),577);
console.log('B47/B57 profiles: verified measurements, no unvalidated B47 regeneration, B57 retained');
